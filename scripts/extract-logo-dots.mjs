// Measure the dots of the UKCEH logo symbol in the logo lock-up image, so the finale can send cubes
// to exactly the places where the dots are. Writes src/logoDots.js.
//
// The symbol is three rings of dots (6 inner, 8 middle, 12 outer, 26 in all) at the left of the
// lock-up. A dot is a connected patch of visible (not transparent) pixels; its centre is the middle
// of the patch and its radius is that of a circle of the same area. Positions are in image pixels.
//
// Usage: node scripts/extract-logo-dots.mjs [path/to/lock-up.png]

import { readFileSync, writeFileSync } from 'node:fs';
import { PNG } from 'pngjs';

const input = process.argv[2] ?? 'assets/UKCEH_Logo_Tagline_Stacked_White_Data.png';
const png = PNG.sync.read(readFileSync(input));
const { width, height, data } = png;

// The symbol is in the left part of the image, above the tagline; the wordmark starts further right.
const regionWidth = Math.round(width * 0.28);
const regionHeight = Math.round(height * 0.8);
const visible = (x, y) => data[(y * width + x) * 4 + 3] > 128;

const seen = new Uint8Array(regionWidth * regionHeight);
const dots = [];
for (let y = 0; y < regionHeight; y++) {
  for (let x = 0; x < regionWidth; x++) {
    if (seen[y * regionWidth + x] || !visible(x, y)) continue;
    const stack = [[x, y]];
    seen[y * regionWidth + x] = 1;
    let area = 0;
    let sumX = 0;
    let sumY = 0;
    while (stack.length) {
      const [a, b] = stack.pop();
      area++;
      sumX += a;
      sumY += b;
      for (const [u, v] of [[a + 1, b], [a - 1, b], [a, b + 1], [a, b - 1]]) {
        if (u >= 0 && v >= 0 && u < regionWidth && v < regionHeight && !seen[v * regionWidth + u] && visible(u, v)) {
          seen[v * regionWidth + u] = 1;
          stack.push([u, v]);
        }
      }
    }
    if (area > 50) dots.push({ x: +(sumX / area).toFixed(1), y: +(sumY / area).toFixed(1), r: +Math.sqrt(area / Math.PI).toFixed(1) });
  }
}

// Order the dots from the outside in, then round the ring, so the file is easy to read.
const middle = {
  x: dots.reduce((s, d) => s + d.x, 0) / dots.length,
  y: dots.reduce((s, d) => s + d.y, 0) / dots.length,
};
dots.sort((a, b) => b.r - a.r || Math.atan2(a.y - middle.y, a.x - middle.x) - Math.atan2(b.y - middle.y, b.x - middle.x));

const radii = [...new Set(dots.map((d) => Math.round(d.r)))];
console.log(`${dots.length} dots found in ${input} (${width} x ${height} px), radii about ${radii.join(', ')} px`);
if (dots.length !== 26) console.warn('Warning: the UKCEH symbol has 26 dots.');

writeFileSync('src/logoDots.js', `// The dots of the UKCEH logo symbol, measured in the logo lock-up image. Generated by
// scripts/extract-logo-dots.mjs from ${input}: do not edit.
// Positions and radii are in image pixels (x across, y down).

export default ${JSON.stringify({ image: { width, height, file: input.split('/').pop() }, dots }, null, 2)};
`);
